def probe(ticker):
    """Yahoo's name for TICKER.SA, or None when Yahoo doesn't have it.
    Throttled or timed-out requests are tried again; only a 404 means
    "not listed"."""
    url = f"https://query1.finance.yahoo.com/v8/finance/chart/{ticker}.SA?interval=1d&range=5d"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    for attempt in range(5):
        try:
            meta = json.load(urllib.request.urlopen(req, timeout=15))["chart"]["result"][0]["meta"]
            name = (meta.get("longName") or meta.get("shortName") or "").strip()
            return ticker, " ".join(name.split()) or None
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return ticker, None
        except Exception:
            pass
        time.sleep(2 * (attempt + 1))
    raise SystemExit(f"Yahoo didn't answer for {ticker}; try again later.")


def main():
    groups = [("Stock", STOCKS), ("Fund", FUNDS), ("Stock", BDRS)]
    rows, missing = [], []
    with cf.ThreadPoolExecutor(4) as ex:
        for kind, tickers in groups:
            for ticker, name in ex.map(probe, dict.fromkeys(tickers)):
                if name:
                    rows.append((ticker, name.replace("\\", "").replace('"', "'"), kind))
                else:
                    missing.append(ticker)
    rows.sort()
    out = pathlib.Path(__file__).resolve().parent.parent / "crates/core/src/b3_list.rs"
    lines = [
        "// Generated by scripts/b3-symbols.py (names from Yahoo). Don't edit by hand.",
        "",
        "/// (ticker, name, kind): B3 symbols search knows without the network.",
        "pub(crate) const B3: &[(&str, &str, crate::AssetKind)] = &[",
    ]
    lines += [f'    ("{t}", "{n}", crate::AssetKind::{k}),' for t, n, k in rows]
    lines += ["];", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} symbols written to {out}")
    if missing:
        print("Not on Yahoo (left out):", " ".join(missing))


if __name__ == "__main__":
    main()
